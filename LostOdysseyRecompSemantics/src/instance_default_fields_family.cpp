bool Apply(GuestAddress address, GuestMemory& memory,
    std::uint64_t incoming_r3, std::uint64_t& result)
{
    const Spec* spec = std::lower_bound(std::begin(kSpecs), std::end(kSpecs),
        address, [](const Spec& entry, GuestAddress target)
        { return entry.address < target; });
    if (spec == std::end(kSpecs) || spec->address != address)
        return false;

    const GuestAddress object = static_cast<GuestAddress>(incoming_r3);
    if (object != 0)
    {
        for (std::uint16_t index = 0; index < spec->write_count; ++index)
        {
            const FieldDefault& field = kWrites[spec->first_write + index];
            const GuestAddress target = object + GuestAddress{field.offset};
            if (field.width == StoreWidth::Byte)
                memory.WriteU8(target,
                    static_cast<std::uint8_t>(field.value));
            else
                memory.WriteU32(target, field.value);
        }
    }
    result = incoming_r3;
    return true;
}

